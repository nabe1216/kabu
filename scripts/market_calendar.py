_warned: set[int] = set()


def is_business_day(d: date) -> bool:
    if d.weekday() >= 5:
        return False
    if d.year not in COVERED_YEARS:
        if d.year not in _warned:
            log.warning('market_calendar: %d年の休業日の表がない（土日と年末年始だけで近似）', d.year)
            _warned.add(d.year)
        return not ((d.month == 12 and d.day == 31) or (d.month == 1 and d.day <= 3))
    return d.isoformat() not in _HOLIDAYS


def prev_business_day(d: date, n: int = 1) -> date:
    """d より前の n 営業日目。"""
    k = 0
    while k < n:
        d -= timedelta(days=1)
        if is_business_day(d):
            k += 1
    return d


def cum_date(y: int, m: int) -> date:
    """月末が権利確定日の銘柄の、権利付き最終日。
    月末以前で最後の営業日（受け渡しが間に合う最後の日）から、2営業日前。"""
    last = date(y + (m // 12), m % 12 + 1, 1) - timedelta(days=1)
    while not is_business_day(last):
        last -= timedelta(days=1)
    return prev_business_day(last, 2)
